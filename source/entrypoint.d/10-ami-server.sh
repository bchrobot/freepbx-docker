# Sourced by docker-entrypoint.sh in the asterisk image.
#
# Provides an AMI login for the `asterisk` shim used by the freepbx and cron containers.
# It lives in manager_custom.conf, which FreePBX's generated manager.conf includes and
# never rewrites. Before FreePBX is installed, a minimal manager.conf includes it too.
file_env AMI_USER freepbx-docker
file_env AMI_PASSWORD
if [[ -z "$AMI_PASSWORD" ]]; then
  echo "error: AMI_PASSWORD or AMI_PASSWORD_FILE must be set" >&2
  exit 1
fi

manager_conf=/etc/asterisk/manager.conf
custom_conf=/etc/asterisk/manager_custom.conf
if ! grep -q 'auto-generated by FreePBX' "$manager_conf" 2>/dev/null; then
  cat >"$manager_conf" <<CONF
; Bootstrap AMI config written by freepbx-docker; replaced by FreePBX on install.
[general]
enabled = yes
port = 5038
bindaddr = 0.0.0.0
displayconnects = no

#include manager_custom.conf
CONF
fi

touch "$custom_conf"
sed -i '/^; BEGIN freepbx-docker/,/^; END freepbx-docker/d' "$custom_conf"
cat >>"$custom_conf" <<CONF
; BEGIN freepbx-docker (managed by the container entrypoint; do not edit)
[${AMI_USER}]
secret = ${AMI_PASSWORD}
deny = 0.0.0.0/0.0.0.0
permit = 127.0.0.1/255.255.255.255
read = system,call,log,verbose,command,agent,user,config,dtmf,reporting,cdr,dialplan,originate,message
write = system,call,log,verbose,command,agent,user,config,dtmf,reporting,cdr,dialplan,originate,message
writetimeout = 5000
; END freepbx-docker
CONF
chown asterisk:asterisk "$manager_conf" "$custom_conf"
chmod 0640 "$custom_conf"
